src = 'D:/Starsector/starsector-core/data/hullmods/hull_mods.csv'
dst = 'D:/Starsector/kr_work/patches/starsectorkorean/data/hullmods/hull_mods.csv'

with open(src, encoding='utf-8', newline='') as f:
    content = f.read()

reader = csv.DictReader(io.StringIO(content))
fieldnames = reader.fieldnames
rows = list(reader)

patched = 0
for row in rows:
    hid = row.get('id', '').strip()
    if hid in TRANS:
        t = TRANS[hid]
        for field in ('name', 'desc', 'short', 'sModDesc'):
            if field in t:
                row[field] = t[field]
        patched += 1

with open(dst, 'w', encoding='utf-8', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator='\n')
    writer.writeheader()
    for row in rows:
        writer.writerow(row)

print(f"Patched {patched} hull mods, wrote {len(rows)} total rows to {dst}")
